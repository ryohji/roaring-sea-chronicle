#!/usr/bin/env python3
"""仮スプライト CHR（chr/sprites.png）を生成する。

**これは絵の完成品ではない。** 本番のドット絵が入ったら役目を終える。
ただし「仮」であっても、次の4つは読めなければ手触りの評価ができない。
P1 の受入で主から挙がった指摘は、すべてこの4点が欠けていたことに起因する。

  1. 向き    — 全ポーズを**右向き**で描く。左向きは OAM の水平反転で作る
  2. 姿勢    — 立ち／歩き／構え／斬り／のけぞり／ダウンを別の絵にする
  3. 役割    — 操作キャラ／仲間／敵を**輪郭で**見分けられるようにする（色だけに頼らない）
  4. 奥行き  — 足元に影を敷く。影の位置がレーン（接地線）そのものになる

8x16・3色では**内側の描き込みは読めない。輪郭だけが読める。**
したがって姿勢の差は次の3つで作る。細部を描き込んでも手触りの判断材料にはならない。

  * 傾き   — 斬りは前（右）へ、のけぞりは後ろ（左）へ倒す。**逆向きに折れる**ので区別がつく
  * 高さ   — 構えは沈む（1段低い）。ダウンは接地線の上だけ
  * 張り出し — 斬りは腕が右端まで伸びる。届く距離そのものは効果スプライト（斬り）が示す

向きの手がかりは**頭の明暗**で作る。後頭部（左）を輪郭色で塗り、顔（右）を明色にする。
線1本の張り出しや目の1ドットは、この大きさでは読めない。**面で割るしか読めない。**

タイルの並び（8x16 モード。画像上は「上半分の右隣が下半分」）:

  タイル行0 (  0..15): 操作キャラ 6姿勢 + 予備
  タイル行1 ( 16..31): 仲間       6姿勢 + 予備
  タイル行2 ( 32..47): 敵         6姿勢 + 予備
  タイル行3 ( 48..63): 効果（影・斬り・衝撃・判定枠）

姿勢の並びは3役割で共通（+0 立ち / +2 歩き / +4 構え / +6 斬り / +8 のけぞり / +10 ダウン）。
src/constants.inc の SPR_POSE_* と対応する。ここを動かすときは両方直すこと。

    python3 tools/mk_placeholder_chr.py
"""
