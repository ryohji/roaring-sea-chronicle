# PNG 上の見た目（確認用。実際の色は ROM 側のパレットが決める）
PALETTE = [(24, 24, 32), (16, 16, 24), (128, 72, 56), (240, 208, 160)] + [(255, 0, 255)] * 252


def blit(rows, tile_index, art):
    """8x16 の絵を、タイル N（上半分）と N+1（下半分）に置く。"""
    if tile_index % 2:
        raise ValueError("8x16 スプライトの先頭タイルは偶数でなければならない: %d" % tile_index)
    for half in (0, 1):
        t = tile_index + half
        ty, tx = divmod(t, 16)
        if ty >= 16:
            raise ValueError("タイル %d は 256 タイルの外" % t)
        for y in range(8):
            line = art[half * 8 + y]
            if len(line) != 8:
                raise ValueError("1行は8文字でなければならない: %r" % line)
            for x, ch in enumerate(line):
                if ch not in INK:
                    raise ValueError("未知の記号 %r" % ch)
                rows[ty * 8 + y][tx * 8 + x] = INK[ch]


def main():
    rows = [bytearray(WIDTH) for _ in range(HEIGHT)]

    for base, poses, name in ((0, PLAYER, "操作キャラ"),
                              (16, ALLY, "仲間"),
                              (32, ENEMY, "敵")):
        for i, pose in enumerate(POSE_ORDER):
            if pose not in poses:
                raise ValueError("%s に姿勢 %s がない" % (name, pose))
            blit(rows, base + i * 2, poses[pose])

    for i, name in enumerate(EFFECT_ORDER):
        blit(rows, 48 + i * 2, EFFECTS[name])

    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "chr", "sprites.png")
    write_indexed_png(out, WIDTH, HEIGHT, rows, PALETTE)
    print("wrote %s (%dx%d)" % (out, WIDTH, HEIGHT))
    print("  姿勢: %s" % " / ".join(POSE_ORDER))
    print("  役割: 操作キャラ=0.. 仲間=16.. 敵=32.. 効果=48..")


if __name__ == "__main__":
    main()
